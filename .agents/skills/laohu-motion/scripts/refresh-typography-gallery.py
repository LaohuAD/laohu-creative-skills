#!/usr/bin/env python3
"""Prepare browser-readable specimen metadata from the Motion font index."""

import argparse
import hashlib
import json
import os
from pathlib import Path
from urllib.parse import quote


SKILL = Path(__file__).resolve().parents[1]
REPO = SKILL.parents[2]
GALLERY = SKILL / "assets" / "typography"
NAMES = {
    "LXGW WenKai": "霞鹜文楷",
    "ZCOOL KuaiLe": "站酷快乐体",
    "Noto Serif SC": "思源宋体",
    "Noto Sans SC": "思源黑体",
    "Source Han Sans CN VF": "思源黑体 CN",
}


def browser_file(descriptor):
    relative = Path(descriptor["path"])
    path = (REPO / relative).resolve()
    if relative.is_absolute() or ".." in relative.parts or SKILL not in path.parents:
        raise ValueError(f"Font gallery descriptor leaves the Skill: {relative}")
    return {
        "name": relative.name,
        "url": quote(Path(os.path.relpath(path, GALLERY)).as_posix(), safe="/"),
        "sha256": descriptor["sha256"],
    }


def make_script():
    source = GALLERY / "fonts.json"
    catalog = source.read_bytes()
    data = json.loads(catalog)
    if data["schema"] != "laohu.motion.typography-fonts/1":
        raise ValueError("Unsupported Motion font index")
    rows = []
    for font in data["entries"]:
        keys = ("id", "family", "category", "coverageScope", "weight", "style", "axes", "scripts", "cmap")
        row = {key: font[key] for key in keys}
        row["label"] = font.get("displayName") or NAMES.get(row["family"], row["family"])
        row["aliases"] = font["aliases"]
        row["summary"] = font["summary"]
        row["upstream"] = font.get("upstream")
        row["variationSequences"] = font.get("variationSequences", {})
        row["copies"] = [
            {
                "source": copy["source"],
                "file": {**browser_file(copy["file"]), "format": copy["file"]["format"]},
                "license": browser_file(copy["license"]) if copy["license"] else None,
            }
            for copy in font["copies"]
        ]
        rows.append(row)
    payload = {"indexSha256": hashlib.sha256(catalog).hexdigest(), "fonts": rows}
    raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return "// Generated by refresh-typography-gallery.py from fonts.json.\nwindow.motionFontGallery = " + raw + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the browser metadata when the index changed")
    args = parser.parse_args()
    script = make_script()
    target = GALLERY / "gallery-data.js"
    matches = target.is_file() and target.read_text(encoding="utf-8") == script
    if not matches and args.write:
        target.write_text(script, encoding="utf-8")
    elif not matches:
        print("Font gallery metadata needs refresh. Run again with --write.")
        return 1
    print(f"{target.relative_to(REPO)} is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
